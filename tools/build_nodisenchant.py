"""Builds Disenchant/NoDE.lua: weapons and armor that can't be disenchanted.

Source: the cMaNGOS classic-db item table (Full_DB/ClassicDB_*.sql.gz, GPL).
  - flag 0x8000 (ITEM_FLAG_NO_DISENCHANT) comes from Blizzard's own item data
    (the client item cache), so those are certain:          [id] = 1
  - items with no disenchant loot table (DisenchantID = 0) can't be disenchanted
    on the emulator either; nearly all are removed/test items: [id] = 2
Only uncommon-epic weapons and armor are listed (everything else is never
disenchantable by the addon's own rules anyway).

usage: python3 tools/build_nodisenchant.py path/to/ClassicDB_1_12_1_zXXXX.sql.gz
"""
import gzip, re, sys

def tuples(s):
    out, depth, q, esc, tup, field = [], 0, False, False, [], []
    for ch in s:
        if q:
            if esc: field.append(ch); esc = False
            elif ch == '\\': esc = True
            elif ch == "'": q = False
            else: field.append(ch)
            continue
        if ch == "'": q = True; continue
        if ch == '(' and depth == 0: depth, tup, field = 1, [], []; continue
        if depth == 1:
            if ch == ',': tup.append(''.join(field)); field = []
            elif ch == ')': tup.append(''.join(field)); out.append(tup); depth = 0
            else: field.append(ch)
    return out

def main(src, dst):
    cols, rows, create = [], [], False
    with gzip.open(src, 'rt', encoding='latin-1') as f:
        for line in f:
            if line.startswith('CREATE TABLE `item_template`'): create = True; continue
            if create:
                m = re.match(r'\s+`(\w+)`', line)
                if m: cols.append(m.group(1))
                if line.startswith(')'): create = False
                continue
            if line.startswith('INSERT INTO `item_template`'):
                rows += tuples(line[line.index('VALUES') + 6:])
    c = {k: cols.index(k) for k in ('entry', 'class', 'Quality', 'Flags', 'DisenchantID', 'name')}
    out = {}
    for r in rows:
        if r[c['class']] not in ('2', '4') or not (2 <= int(r[c['Quality']]) <= 4): continue
        if int(r[c['Flags']]) & 0x8000: out[int(r[c['entry']])] = (1, r[c['name']])
        elif r[c['DisenchantID']] == '0': out[int(r[c['entry']])] = (2, r[c['name']])
    with open(dst, 'w', encoding='utf-8') as f:
        f.write('-- Generated by tools/build_nodisenchant.py from the cMaNGOS classic-db item table (GPL).\n')
        f.write('-- Weapons and armor (uncommon to epic) that can\'t be disenchanted.\n')
        f.write('-- 1 = Blizzard\'s "no disenchant" item flag; 2 = no disenchant loot table.\n')
        f.write('local _, FI = ...\nFI.NoDisenchant = {\n')
        for i in sorted(out):
            kind, name = out[i]
            f.write('  [%d] = %d, -- %s\n' % (i, kind, name.replace('\n', ' ')))
        f.write('}\n')
    print(len(out), 'items;', sum(1 for v in out.values() if v[0] == 1), 'flagged')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else 'Disenchant/NoDE.lua')
